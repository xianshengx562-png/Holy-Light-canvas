/**
 * 「自定义接口」这一档**显不显示**（2026-09-29，修「有时候会消失」那一条）。
 *
 * ## 它修的是什么
 *
 * 引擎下拉里「自定义接口」是唯一一个**依赖外部有没有配过东西**才存在的档位
 * （见 `lib/workflows/imageEngine.ts` 文件头）：一个出图模型都没有时把它列出来，
 * 用户点下去只能拿到一句「还没配置」。
 *
 * 可「一个都没有」这个结论**只有在那一趟请求成功回来之后才成立**。而它偏偏会失败：
 * 桌面版的数据请求走主进程转发给**另一个进程**的命名管道，那个进程还没 ready、
 * 或者崩了正在重启，页面拿到的就是一个 503。以前那一趟失败之后
 * `useApi` 的 `data` 一直是 `null`，界面把它当成「确认过：一个都没有」——
 * 于是「自定义接口」这一档整场会话都不见了，直到用户切走再切回来重新挂载组件。
 * 用户看到的就是「有时候会消失」。
 *
 * ## 这里的规矩
 *
 * **没问到 ≠ 没有。** 只有「请求成功回来了，并且确实是 0 个」才隐藏；
 * 还在问、或者问失败了，都按「还在」处理 —— 留着一个也许用不了的选项，
 * 也比把一个正在用的档位悄悄藏起来好（藏起来之后节点上存着的 `engine: 'custom'`
 * 会被显示成「自定义接口 · 当前用不了」，那是彻头彻尾的假象）。
 *
 * ⚠️ 这个模块**不能** import `server-only` 的东西：渲染进程（下拉）与回归脚本
 *    （单测）都要直接加载它，理由同 `lib/providers/site-quota.ts`。
 */

export type CustomListState = {
  /** 这一趟清单**成功**问到过没有。还没问到 = false（正在加载，或者失败了）。 */
  loaded: boolean;
  /** 问到的时候有几个对应用途的模型。 */
  count: number;
};

/**
 * 下拉里要不要列出「自定义接口」这一档。
 *
 * 三种情况：
 * - 还没问到（加载中 / 请求失败）→ **列出来**。这时候隐藏它等于替用户做了「你没配」的判断，
 *   而这个判断我们根本没有依据；代价只是没配接口的用户会在加载的那一小会儿看见它。
 * - 问到了、有模型 → 列出来（本来就该列）。
 * - 问到了、一个都没有 → **不列**。这才是「没配就不显示」原本要说的情况。
 */
export function customEngineVisible(state: CustomListState): boolean {
  return !state.loaded || state.count > 0;
}
