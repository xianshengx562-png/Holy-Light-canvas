/**
 * 任务轮询的**节奏**（2026-09-29 定；2026-09-30：不做任何「按等待时长下结论」的事）。
 *
 * ## 它修的是什么
 *
 * 原来是「固定 3 秒一趟」：一个任务跑满就是几百次请求，批量跑十几个节点时请求数
 * 直接放大，而视频往往要好几分钟 —— 把上游（或网关那点限流额度）撞光的正是我们自己。
 *
 * ## 这里的规矩
 *
 *  - **越等越慢**：刚提交时结果可能马上就来（同步出图那种毫秒级场景不能掉队），
 *    久了就该拉长间隔 —— 视频几分钟是常态，3 秒一次没有意义。
 *  - 🔴 **只管节奏，不做任何「按等待时长下结论」的事**（2026-09-30 定死）：
 *    任务只有成功与失败两种结果，跑多久是上游的事。这里没有等待上限、不自动结单，
 *    也不会替用户把它判失败 —— 想停只能由用户自己点「放弃这一轮」。
 *
 * ⚠️ 这个文件**不能** import `server-only`：画布（渲染进程）与回归脚本都要加载它。
 */

/**
 * 等过这么久之后，就一直按最慢那一档问下去。
 *
 * ⚠️ 它只是**分档用的边界**，不是等待上限：跑过这么久之后仍然按最后一档的节奏继续问，
 * 一直到上游给出成功或失败。别把它（或任何别的时间值）当成「可以放弃了」的信号 ——
 * 那等于替用户撕掉一张本来会出片的单子。
 */
export const SLOWEST_AFTER_MS = 20 * 60 * 1000;

/**
 * 轮询档位：**按已经等了多久**决定下一次隔多久（不是按次数 —— 次数会随档位变化而失去意义）。
 *
 * 开头密一点是为了不拖慢「提交完几秒就出结果」的场景；后面拉长是为了省请求。
 */
export const POLL_STEPS: { untilMs: number; delayMs: number }[] = [
  { untilMs: 30_000, delayMs: 3_000 },
  { untilMs: 3 * 60_000, delayMs: 6_000 },
  { untilMs: 10 * 60_000, delayMs: 12_000 },
  { untilMs: SLOWEST_AFTER_MS, delayMs: 20_000 },
];

/** 第一次等待的间隔（0 秒还没过去，取第一档）。单独导出，界面和探针都能对上账。 */
export const FIRST_POLL_DELAY_MS = POLL_STEPS[0].delayMs;

/**
 * 下一次该等多久。**永远有下一趟**，返回值永远是一个正数毫秒。
 *
 * `elapsedMs` 是「从提交到现在过了多久」。传进来的不是数字（NaN / undefined）时
 * 按 0 处理 —— 拿不到起点不该让轮询直接停掉。
 *
 * ⚠️ 这里**不存在**任何「等太久就停下」的分支：跑多久是上游的事，我们不替它做决定。
 */
export function pollDelayMs(elapsedMs: number): number {
  const at = Number.isFinite(elapsedMs) ? Math.max(0, elapsedMs) : 0;
  for (const step of POLL_STEPS) {
    if (at < step.untilMs) return step.delayMs;
  }
  return POLL_STEPS[POLL_STEPS.length - 1].delayMs;
}


/**
 * 用户自己点「放弃这一轮」时那一句（2026-09-29）。
 *
 * 这是现在**唯一**一种结单原因 —— 任务只有成功与失败，跑多久是上游的事，
 * 所以这句话只可能由用户自己点出来。
 */
export function abandonMessage(): string {
  /*
   * ⚠️ 不要写「积分已退回」（2026-09-29 改）：工作流那一路跑的是用户自己的账号，
   *    我们压根没扣钱 —— 说了一句不存在的话，比什么都不说更糟（用户会以为钱动过）。
   */
  return '这一轮被放弃了 —— 已按失败处理。';
}
